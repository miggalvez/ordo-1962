// Bundle data/*.json into src/generated/data.ts so the ESM and CommonJS builds
// both carry the catalogue without reading files at runtime.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const read = (path) => JSON.parse(readFileSync(new URL(`../data/${path}`, import.meta.url), 'utf8'));

const sources = {
  CATALOGUE: ['catalogue.json', 'readonly CatalogueEntry[]'],
  TEMPORAL_BLOCKS: ['temporal-blocks.json', 'Readonly<Record<TemporalBlockName, readonly (readonly string[])[]>>'],
  LAYERS: [null, 'Readonly<Record<string, Layer>>'],
};

const layers = { pl: read('layers/pl.json') };
const lines = [
  '// Generated by scripts/generate-data.mjs from data/. Do not edit.',
  "import type { CatalogueEntry, Layer, TemporalBlockName } from '../types.js';",
  '',
];
for (const [name, [file, type]] of Object.entries(sources)) {
  const value = file ? read(file) : layers;
  lines.push(`export const ${name}: ${type} = ${JSON.stringify(value)};`, '');
}

const dir = new URL('../src/generated/', import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL('data.ts', dir), lines.join('\n'));
